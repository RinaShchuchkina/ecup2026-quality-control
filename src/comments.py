def _find_quote(text: str, pat: str) -> Optional[str]:
    m = re.search(pat, text)
    if not m:
        return None
    s = max(0, m.start() - 25)
    e = min(len(text), m.end() + 25)
    frag = text[s:e].strip()
    frag = re.sub(r"\s+", " ", frag)
    if s > 0:
        frag = "…" + frag
    if e < len(text):
        frag = frag + "…"
    return frag[:110]


def make_comment(name: str, description: str, category: str, pred: int) -> str:
    raw = f"{name} {description}"
    text = _TAG.sub(" ", raw).lower()
    key = (category, pred)
    if key not in _CAT_PHRASE:
        key = ("БАД", pred)
    concl, rules = _CAT_PHRASE[key]
    for pat, phrase in rules:
        q = _find_quote(text, pat)
        if q:
            comment = f"В карточке указано: «{q}» — {phrase}, поэтому {concl}."
            break
    else:
        short = re.sub(r"\s+", " ", _TAG.sub(" ", str(name))).strip()[:60]
        tail = _FALLBACK[key]
        comment = (f"Проверены название «{short}», описание и фотографии упаковки: {tail}"
                   if short else tail)
    comment = comment[0].upper() + comment[1:]
    if len(comment) > MAX_LEN:
        cut = comment.rfind(" ", 0, MAX_LEN - 1)
        comment = comment[:cut if cut > MIN_LEN else MAX_LEN - 1] + "…"
    if len(comment) < MIN_LEN:
        comment = (comment + " " + _FALLBACK[key])[:MAX_LEN]
    return comment


def format_result(comment: str, pred: int) -> str:
    verdict = "не бан" if pred == 1 else "бан"
    return f"<комментарий>{comment}<вердикт>{verdict}"


_RESULT_RE = re.compile(r"^<комментарий>(.{50,300}?)<вердикт>(бан|не бан)$", re.S)


def validate_submission(df) -> List[str]:
    errors = []
    if list(df.columns) != ["id", "result"]:
        errors.append(f"колонки {list(df.columns)}, ожидались ['id','result']")
    if df["id"].duplicated().any():
        errors.append("дубли id")
    if df["result"].isna().any():
        errors.append("NaN в result")
    bad = [i for i, r in zip(df["id"], df["result"].astype(str)) if not _RESULT_RE.match(r)]
    if bad:
        errors.append(f"{len(bad)} строк не соответствуют формату, примеры id: {bad[:5]}")
    return errors
